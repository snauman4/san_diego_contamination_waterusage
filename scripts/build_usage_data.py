"""Join State Water Board monthly supplier data to service-area boundaries -> ../../sd-water-data.js

Sources (downloaded 2026-11-05):
  sd_monthly.csv  : San Diego County rows of the State Water Board "Urban Retail Water Supplier -
                    Water Conservation, Supply, and Demand" monthly dataset (data.ca.gov)
  bounds.geojson  : System Area Boundary Layer polygons for the suppliers in that dataset
  all371.geojson  : every San Diego County (CA371*) system boundary, drawn as grey context

Run:  python3 -I build_data.py
"""
import csv, json, os, collections
from datetime import date

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', '..', 'sd-water-data.js')

def num(x):
    try: return float(x)
    except (TypeError, ValueError): return None

rows = list(csv.DictReader(open(os.path.join(HERE, 'sd_monthly.csv'))))
by = collections.defaultdict(list)
for r in rows: by[r['WATER_SYSTEM_ID']].append(r)

GAL_PER_AF = 325851.0
SECT = [('res', 'POTABLE_DEMAND_RES_GAL'), ('cii', 'POTABLE_DEMAND_CII_GAL'),
        ('irr', 'POTABLE_DEMAND_IRR_GAL'), ('ag', 'POTABLE_DEMAND_AG_GAL'),
        ('oth', 'POTABLE_DEMAND_O_GAL')]

suppliers = {}
for sid, v in by.items():
    v.sort(key=lambda r: r['REPORT_PERIOD_END_DATE'], reverse=True)
    last = v[:12]; last.reverse()                     # most recent 12 reported months, oldest first
    s = {'name': v[0]['SUPPLIER_NAME'], 'ids': sid.split(','),
         'period': [last[0]['REPORT_PERIOD_START_DATE'], last[-1]['REPORT_PERIOD_END_DATE']]}
    days = pop_days = res = 0.0
    sect = {k: 0.0 for k, _ in SECT}
    supply = sold = 0.0
    monthly = []
    for r in last:
        d0 = date.fromisoformat(r['REPORT_PERIOD_START_DATE']); d1 = date.fromisoformat(r['REPORT_PERIOD_END_DATE'])
        nd = (d1 - d0).days + 1; pop = num(r['POP_REPORT_PERIOD']) or 0
        days += nd; pop_days += pop * nd
        for k, c in SECT: sect[k] += num(r[c]) or 0
        supply += num(r['POTABLE_SUPPLY_GAL']) or 0; sold += num(r['POTABLE_VOL_SOLD_GAL']) or 0
        rg = num(r['POTABLE_DEMAND_RES_GAL'])
        monthly.append({'m': r['REPORT_PERIOD_START_DATE'][:7],
                        'rgpcd': round(rg / pop / nd, 1) if rg and pop else None})
    s['pop'] = round(pop_days / days)
    s['supplyMG'] = round(supply / 1e6, 1)
    s['soldMG'] = round(sold / 1e6, 1)
    s['rgpcd'] = round(sect['res'] / pop_days, 1)
    s['tgpcd'] = round((supply - sold) / pop_days, 1)       # total potable produced, net of water sold on to other agencies
    s['demandAF'] = round(sum(sect.values()) / GAL_PER_AF)
    s['sectorsMG'] = {k: round(x / 1e6, 1) for k, x in sect.items()}
    s['monthly'] = monthly
    # sanity check: reported sector demand cannot sensibly exceed what was supplied
    tot = sum(sect.values())
    net = supply - sold
    if supply and tot > 1.5 * supply:
        s['suspect'] = 'Reported sector demand is larger than total supply (likely a unit/reporting error in the state data).'
    elif net and tot < 0.5 * net:
        s['suspect'] = 'Reported sector demand covers under half of the water supplied, so the residential/sector split looks incomplete.'
    else:
        s['suspect'] = None
    if s['suspect']:   # keep the unreliable sector-based values out of every residential/sector figure
        s['rgpcd'] = None; s['demandAF'] = None; s['sectorsMG'] = None
        for m in s['monthly']: m['rgpcd'] = None
    suppliers[sid] = s

# --- geometry ---
bounds = json.load(open(os.path.join(HERE, 'bounds.geojson')))
id2sup = {i: sid for sid, s in suppliers.items() for i in s['ids']}
feats = []
for f in bounds['features']:
    pid = f['properties']['SABL_PWSID']
    sid = id2sup.get(pid)
    if not sid: continue
    feats.append({'type': 'Feature', 'geometry': f['geometry'],
                  'properties': {'pwsid': pid, 'boundaryName': f['properties']['WATER_SYSTEM_NAME'], 'sid': sid}})
ctx = json.load(open(os.path.join(HERE, 'all371.geojson')))
have = {f['properties']['pwsid'] for f in feats}
ctxf = [{'type': 'Feature', 'geometry': f['geometry'],
         'properties': {'name': f['properties']['WATER_SYSTEM_NAME']}}
        for f in ctx['features'] if f['properties']['SABL_PWSID'] not in have]

data = {'suppliers': suppliers,
        'boundaries': {'type': 'FeatureCollection', 'features': feats},
        'context': {'type': 'FeatureCollection', 'features': ctxf}}
with open(OUT, 'w') as fh:
    fh.write('/* generated by data/sd_water/build_data.py */\nconst SD_DATA = ')
    json.dump(data, fh, separators=(',', ':'))
    fh.write(';\n')
print(len(suppliers), 'suppliers;', len(feats), 'polygons;', len(ctxf), 'context polygons;', os.path.getsize(OUT) // 1024, 'KB')
for sid, s in sorted(suppliers.items(), key=lambda kv: -(kv[1]['rgpcd'] or 0)):
    print(f"{s['name'][:40]:40} R-GPCD {s['rgpcd']}  T-GPCD {s['tgpcd']}  AF {s['demandAF']}  suspect={bool(s['suspect'])}")
